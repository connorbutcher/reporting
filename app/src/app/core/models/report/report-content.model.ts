import { ReportFilter } from '../filter';
import { AccessLevel } from '../permission';
import { Widget } from './widget.model';

/** A report's identity and folder placement — everything except its content. */
export type ReportSummary = {
  id: number;
  number: number;
  name: string;
  folderId: number | null;
  /**
   * Whether the report has a checked-out draft. The server only ever reports this as true to a
   * caller who can edit the report, so a viewer never learns a draft exists — treat it as an
   * editor-only signal.
   */
  hasDraft: boolean;
  latestVersionNumber: number | null;
  /** The current user's effective access to this report — drives whether editing is offered. */
  accessLevel: AccessLevel;
  /** Whether the current user has starred this report. */
  isFavorite: boolean;
  modifiedAt: string;
};

/** The user's saved viewing filters as the viewer's encoded string (opaque to the server); null when none. */
export type ReportViewFiltersState = {
  filters: string | null;
};

/** A shared filter snapshot by the short `id` a link carries. `filters` is null when the report has none with that id. */
export type ReportSharedView = {
  id: string;
  filters: string | null;
};

/** Whether a candidate report name is free among its siblings, for live validation as the user types. */
export type ReportNameAvailable = {
  available: boolean;
};

/** One tab of a revision: a grid surface with its own dimensions and widgets. */
export type Tab = {
  /** Stable logical id (the entity's RefId), generated by the client. */
  id: string;
  name: string;
  order: number;
  columns: number;
  rows: number;
  widgets: Widget[];
};

/** The content of one revision of a report — either the checked-out draft or one published version. */
export type ReportRevisionContent = {
  reportId: number;
  name: string;
  /** The revision's tabs, ordered; each carries its own grid and widgets. */
  tabs: Tab[];
  /** Rich-text (HTML) description of what changed. Null for drafts. */
  notes: string | null;
  /** Report-level filters, one per dataset, applied on top of each widget's own. */
  filters: ReportFilter[];
};

export type ReportVersionSummary = {
  versionNumber: number;
  publishedAt: string;
  /** Rich-text (HTML) description of what changed in this version, entered when publishing. */
  notes: string | null;
};

/** A report match from a name/number search, with its folder location for display. */
export type ReportSearchResult = {
  id: number;
  number: number;
  name: string;
  /** Editor-only signal — see {@link ReportSummary.hasDraft}. */
  hasDraft: boolean;
  latestVersionNumber: number | null;
  /** The current user's effective access to this report — drives whether editing is offered. */
  accessLevel: AccessLevel;
  /** Whether the current user has starred this report. */
  isFavorite: boolean;
  modifiedAt: string;
  folderPath: string;
};
